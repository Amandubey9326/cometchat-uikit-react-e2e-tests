"""Rebuilds docs/sheet-coverage.md: each case of CometChat_Features_All_Test_Cases.xlsx and the test covering it.

docs/sheet-cases.json holds every case with its manual classification. Tests whose title starts with a
sheet ID in dash form (e.g. "ADVSEARCH-001/002 …", "MSG-021/025 …") mark those cases as covered.
Usage: python3 scripts/sheet_coverage.py
"""
import json, re
from collections import OrderedDict

ROOT = __file__.rsplit('/scripts/', 1)[0]
cases = json.load(open(f'{ROOT}/docs/sheet-cases.json'), object_pairs_hook=OrderedDict)
PREFIXES = {k.rsplit('_', 1)[0] for k in cases}

found = {}
# Real titles (templates resolved) from Playwright's test list.
import subprocess
listing = subprocess.run(['npx', 'playwright', 'test', '--list'], cwd=ROOT, capture_output=True, text=True).stdout
for m in re.finditer(r"› ([A-Z]+)-(\d{3})((?:/\d{3})*)\s", listing):
    prefix, first, rest = m.group(1), m.group(2), m.group(3)
    if prefix not in PREFIXES:
        continue
    label = f'{prefix}-{first}{rest}'
    for n in [first] + [x for x in rest.split('/') if x]:
        found[f'{prefix}_{n}'] = label

for cid, label in found.items():
    if cid in cases and cases[cid]['status'] not in ('Not in 7.0.3 / N/A',):
        cases[cid].update(status='Covered', test=label)

order = ['Covered', 'Partly', 'Not covered', 'Blocked', 'Not in 7.0.3 / N/A']
icon = {'Covered': '✅', 'Partly': '🟡', 'Not covered': '❌', 'Blocked': '⛔', 'Not in 7.0.3 / N/A': '➖'}
tabs = OrderedDict()
for cid, c in cases.items():
    tabs.setdefault(c['tab'], []).append((cid, c))

L = ['# Coverage vs "CometChat_Features_All_Test_Cases.xlsx"', '',
     '_Generated by `python3 scripts/sheet_coverage.py` from `docs/sheet-cases.json` and the test titles._', '',
     '✅ Covered — an automated test exists · 🟡 Partly · ❌ Not covered · ⛔ Blocked (needs a setting turned on) · ➖ Not in UIKit 7.0.3 / not applicable to the web app', '',
     '## Summary', '', '| Tab | Cases | ✅ | 🟡 | ❌ | ⛔ | ➖ |', '|---|---|---|---|---|---|---|']
tot = {k: 0 for k in order}
for tab, rows in tabs.items():
    c = {k: 0 for k in order}
    for _, x in rows:
        c[x['status']] += 1
    for k in order:
        tot[k] += c[k]
    L.append(f'| {tab} | {len(rows)} | ' + ' | '.join(str(c[k]) for k in order) + ' |')
n = sum(tot.values())
L.append(f'| **Total** | **{n}** | ' + ' | '.join(f'**{tot[k]}**' for k in order) + ' |')
applicable = n - tot['Not in 7.0.3 / N/A']
L += ['', f"Of the **{applicable}** cases that apply to UIKit 7.0.3, **{tot['Covered']} ({round(tot['Covered'] * 100 / applicable)}%)** have an automated test.", '',
      '> Tests added for the sheet are written but must be run once; failures are triaged into test fixes or new findings.', '']
for tab, rows in tabs.items():
    L += [f'## {tab}', '', '| ID | Test case | Status | Our test | Note |', '|---|---|---|---|---|']
    for cid, x in rows:
        L.append(f"| {cid} | {x['title'].replace('|', '/')[:110]} | {icon[x['status']]} {x['status']} | {x['test']} | {x['note']} |")
    L.append('')
open(f'{ROOT}/docs/sheet-coverage.md', 'w').write('\n'.join(L))
print(' '.join(f'{k}:{v}' for k, v in tot.items()))
